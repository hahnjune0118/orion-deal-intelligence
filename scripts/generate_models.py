def _reject_constant(value: str) -> None:
    raise ValueError("non-finite JSON numbers are forbidden")


def _object_pairs(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate JSON object keys are forbidden")
        result[key] = value
    return result


def validate_envelope(data: Any) -> DealState | StagedEvidenceUpdate | ExpectedTransition:
    """Validate JSON/dict input without coercion, unknown fields or silent keys.

    This validates structure, not cross-record grounding or analyst authority.
    ExpectedTransition is evaluation-only and must never become model input.
    """
    if isinstance(data, (str, bytes, bytearray)):
        data = json.loads(data, parse_constant=_reject_constant, object_pairs_hook=_object_pairs)
    return ENVELOPE_ADAPTER.validate_python(data, strict=True)


def envelope_json_schema() -> dict[str, Any]:
    """Return the generated Pydantic schema (descriptive metadata may differ)."""
    return ENVELOPE_ADAPTER.json_schema()
