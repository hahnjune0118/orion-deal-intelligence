def annotation(s: dict, owner: str, field: str, inline: list) -> str:
    if '$ref' in s:
        return s['$ref'].rsplit('/', 1)[-1]
    if 'anyOf' in s:
        return ' | '.join(annotation(v, owner, field, inline) for v in s['anyOf'])
    if 'oneOf' in s:
        return 'Annotated[' + ' | '.join(annotation(v, owner, field, inline) for v in s['oneOf']) + ', Field(discriminator="kind")]'
    if 'const' in s:
        value = s['const']
        if value is True:
            return 'Annotated[Literal[True], BeforeValidator(_true)]'
        if type(value) is int:
            return 'Annotated[Literal[0], BeforeValidator(_zero)]'
        return f'Literal[{value!r}]'
    if 'enum' in s:
        return 'Literal[' + ', '.join(repr(v) for v in s['enum']) + ']'
    t=s['type']
    if t=='null': return 'None'
    if t=='object':
        name = owner + ''.join(v.capitalize() for v in field.split('_'))
        inline.append((name,s))
        return name
    if t=='string' and s.get('format')=='date': return 'DateString'
    if t=='string' and s.get('format')=='date-time': return 'UTCString'
    if t=='array':
        base='list['+annotation(s['items'],owner,field,inline)+']'
    else:
        base={'string':'str','integer':'int','number':'int | float','boolean':'bool'}[t]
    args=[]
    for key,target in [('minimum','ge'),('maximum','le'),('minLength','min_length'),('maxLength','max_length'),('minItems','min_length'),('maxItems','max_length'),('pattern','pattern')]:
        if key in s: args.append(f'{target}={s[key]!r}')
    if s.get('uniqueItems'):args.append('json_schema_extra={"uniqueItems": True}')
    annotations=[]
    if args: annotations.append('Field('+', '.join(args)+')')
    if s.get('uniqueItems'):annotations.append('AfterValidator(_unique)')
    if t == 'number': annotations.append('WithJsonSchema(' + repr(s) + ')')
    if annotations:return 'Annotated['+base+', '+', '.join(annotations)+']'
    return base


def generate_class(name,s):
    inline=[]
    body=[]
    for field,prop in s['properties'].items():
        body.append(f'    {field}: {annotation(prop,name,field,inline)}')
    pre=''.join(generate_class(n,v) for n,v in inline)
    result='\n\nclass '+name+'(StrictContract):\n'+'\n'.join(body)+'\n'
    if s.get('allOf'):
        result+='\n    model_config = ConfigDict(json_schema_extra='+pprint.pformat({'allOf':s['allOf']},width=100).replace('\n','\n    ')+')\n'
    if name in CONDITIONALS: result+='\n'+CONDITIONALS[name]
    return pre+result

