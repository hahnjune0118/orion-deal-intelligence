def _date(value: str) -> str:
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", value):
        raise ValueError("date must use YYYY-MM-DD")
    date.fromisoformat(value)
    return value


def _utc_timestamp(value: str) -> str:
    if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}[Tt][0-9]{2}:[0-9]{2}:[0-9]{2}(?:\\.[0-9]+)?Z", value):
        raise ValueError("timestamp must be an ISO-8601 UTC string ending in Z")
    datetime.fromisoformat(value)
    return value


def _unique(values: list[Any]) -> list[Any]:
    if len(values) != len(set(values)):
        raise ValueError("array items must be unique")
    return values


def _true(value: Any) -> bool:
    if type(value) is not bool or value is not True:
        raise ValueError("synthetic must be the JSON boolean true")
    return value


def _zero(value: Any) -> int:
    if type(value) is not int or value != 0:
        raise ValueError("expected_live_api_calls must be integer zero")
    return value


DateString = Annotated[str, AfterValidator(_date), WithJsonSchema({"type": "string", "format": "date"})]
